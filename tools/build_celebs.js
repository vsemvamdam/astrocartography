/* Builds js/celebs-data.js for the "Звёзды" mode from tools/celebs.tsv.

   tools/celebs.tsv is checked by hand: one row per person whose birth time comes from a birth certificate
   or birth record (Rodden rating AA), from the person's own words (A) or from a biography (B), as given on
   the person's Astrotheme page (which cites the source and the rating). People with an unknown, rectified,
   disputed or unsourced time are not included.

   Local time → UTC: the time zone database, except before standard time came in (an offset that is not a
   whole quarter of an hour is a city's local mean time): then the birthplace's own local mean time is used,
   as birth registers did. France 1891–1911 kept Paris mean time by law, so it is taken as it is.

   Usage: ASTRONOMY_JS=/path/to/astronomy-engine node tools/build_celebs.js */
'use strict';
const fs = require('fs');
const path = require('path');
global.window = global;
global.Astronomy = require(process.env.ASTRONOMY_JS || 'astronomy-engine');
const ROOT = path.join(__dirname, '..');
for (const f of ['chiron-data', 'acg-core', 'natal']) require(path.join(ROOT, 'js', f + '.js'));
const ACG = window.ACG, N = window.NATAL;

const POINTS = ['Sun', 'Moon', 'Mercury', 'Venus', 'Mars', 'Jupiter', 'Saturn', 'Uranus', 'Neptune', 'Pluto', 'Node', 'Chiron'];
const rows = fs.readFileSync(path.join(__dirname, 'celebs.tsv'), 'utf8').trim().split('\n').map((l) => l.split('\t'));
const head = rows.shift();
const col = Object.fromEntries(head.map((h, i) => [h, i]));

function toUtc(date, time, tz, lon) {
  const [y, m, d] = date.split('-').map(Number), [hh, mi] = time.split(':').map(Number);
  const conv = ACG.localToUtc(y, m, d, hh, mi, tz);
  let off = conv.offset, lmt = false;
  const day = Date.UTC(y, m - 1, d);
  const pmt = tz === 'Europe/Paris' && day >= Date.UTC(1891, 2, 16) && day < Date.UTC(1911, 2, 11);
  if (off % 15 !== 0 && !pmt) { off = Math.round(lon * 4 * 10) / 10; lmt = true; }
  return { utc: Date.UTC(y, m - 1, d, hh, mi) - Math.round(off * 60000), off, lmt };
}

const slug = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const list = rows.map((r) => {
  const g = (k) => r[col[k]];
  const lat = +g('lat'), lon = +g('lon');
  const t = toUtc(g('date'), g('time'), g('tz'), lon);
  const chart = ACG.computeChart(t.utc, { node: 'true' });
  const nat = N.computeNatal(chart, lat, lon, { house: 'P', minor: false, points: () => true, anglesAspects: false });
  const lonOf = (id) => { const b = chart.bodies.find((x) => x.id === id); return b ? +b.elon.toFixed(2) : null; };
  return {
    id: slug(g('en')), ru: g('ru'), en: g('en'), cat: g('cat'), who: g('who'),
    d: g('date'), t: g('time'), off: t.off, lmt: t.lmt || undefined, utc: t.utc,
    place: g('place'), lat, lon, tz: g('tz'),
    r: g('rating'), src: g('source'), url: g('url'),
    p: POINTS.map(lonOf).concat([+nat.asc.toFixed(2), +nat.mc.toFixed(2)]),
  };
});
const ids = new Set();
for (const c of list) { if (ids.has(c.id)) throw new Error('duplicate ' + c.id); ids.add(c.id); }

const out = `/* Well-known people with a sourced birth time, for the "Звёзды" mode. Generated by tools/build_celebs.js
   from tools/celebs.tsv: birth data as given on each person's Astrotheme page, which cites Astro-Databank
   and the Rodden rating (AA birth record, A the person's own words, B biography).
   p: ecliptic longitudes of ${POINTS.join(', ')}, ASC, MC. */
window.ACG_CELEBS = ${JSON.stringify({ points: POINTS.concat(['ASC', 'MC']), list })};
`;
fs.writeFileSync(path.join(ROOT, 'js', 'celebs-data.js'), out);
console.log(list.length, 'people,', out.length, 'bytes;', list.filter((c) => c.lmt).map((c) => `${c.en} LMT ${c.off}`).join('; '));
