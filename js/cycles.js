    const bday = (age) => Date.UTC(b.getUTCFullYear() + age, b.getUTCMonth(), b.getUTCDate(), b.getUTCHours(), b.getUTCMinutes());
    let age = 0;
    while (bday(age + 1) <= now) age++;
