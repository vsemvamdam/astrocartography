      const o = m.other.id, k = aspKind(m.x), w = m.x.orb <= 2 ? 1.5 : 1;
      if (BENEF.has(o)) { if (k === 'hard') s -= 0.3; else { s += 1.5 * w; plus.push(m.head); } }
