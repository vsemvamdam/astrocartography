  // the parent's chart against the child's: the closest contacts only
  function contacts(par, nat, ctx) {
    const pa = (id) => par.points.find((p) => p.id === id), ch = (id) => nat.points.find((p) => p.id === id);
    const ASP = [[0, 'соединение'], [60, 'секстиль'], [90, 'квадрат'], [120, 'трин'], [180, 'оппозиция']], found = [];
    for (const key of Object.keys(PARENT)) {
      const [a, b] = key.split('|'), A = pa(a), B = ch(b);
      if (!A || !B) continue;
      const sep = Math.abs(n180(A.lon - B.lon)), orbMax = a === 'Moon' || a === 'Sun' || b === 'Moon' || b === 'Sun' ? 6 : 5;
      for (const [angle, ru] of ASP) {
        const orb = Math.abs(sep - angle);
        if (orb > orbMax || (ctx.noTime && b === 'Moon' && orb > 2)) continue;
        const tense = angle === 90 || angle === 180 || (angle === 0 && (a === 'Mars' || a === 'Saturn'));
        found.push({ orb, it: { id: b, tone: tense ? 'hard' : 'soft', head: `${YOUR[a]} и ${CHILD_OF[b]} ребёнка: ${ru}`, text: PARENT[key][tense ? 1 : 0] } });
      }
    }
    const items = found.sort((x, y) => x.orb - y.orb).slice(0, 6).map((x) => x.it);
    const m1 = signOf(pa('Moon').lon) % 4, m2 = signOf(ch('Moon').lon) % 4, rel = m1 === m2 ? 0 : m1 % 2 === m2 % 2 ? 1 : 2;
    return [{ id: 'Moon', head: `${ctx.name ? `Вы и ${ctx.name}` : 'Вы и ребёнок'}: Луна в стихиях «${EL_NOM[m1].toLowerCase()}» и «${EL_NOM[m2].toLowerCase()}»`, text: MOONS_EL[rel] }, ...items];
  }

  function ageItems(nat, ctx) {
    const now = Date.now(), age = (now - ctx.birth) / YEAR, items = [];
    const P = (id) => nat.points.find((p) => p.id === id);
    for (const a of AGES) {
      const on = age >= a.from && age < a.to, p = P(a.id);
      items.push({ id: a.id, tone: on ? 'soft' : undefined, head: `${on ? 'Сейчас: возраст' : 'Возраст'} ${a.n}, ${a.from}–${yearsText(a.to)}`, text: `${a.t} ${p.ru} ребёнка ${inSign(signOf(p.lon))}.` });
    }
    const C = root.CYCLES;
    if (C) {
      const pts = nat.points.filter((p) => ['Jupiter', 'Saturn', 'Uranus', 'Node'].includes(p.id));
      for (const x of C.lifeCycles(pts, ctx.birth, 23)) {
        const m = MILES[`${x.id}|${x.asp}|${x.dir}`];
        if (!m || x.nth !== 1 || x.age > 22.6) continue;
        const d = new Date(x.t), state = x.last < now - 60 * DAY ? 'прошло' : x.t > now + 60 * DAY ? 'впереди' : 'сейчас';
        items.push({ id: x.id, tone: state === 'сейчас' ? 'soft' : undefined, head: `${m[0]}: около ${aroundYears(Math.round(x.age))}, ${MONTHS[d.getMonth()]} ${d.getFullYear()} (${state})`, text: m[1] });
      }
    }
    return items;
  }

